const C_TO_K = 273.15;
const isMetal = (e: Element) => !['nonmetal', 'halogen', 'noble-gas', 'metalloid'].includes(e.category);
const mainGroup = (e: Element) => e.block === 's' || e.block === 'p';

/** Main-group elements whose first ionization energy dips below the element before them. */
const ieDips = ELEMENTS.filter((e) => {
  if (e.z === 1 || e.symbol === 'He' || !mainGroup(e) || e.ionizationEnergy == null) return false;
  const prev = el(e.z - 1).ionizationEnergy;
  return prev != null && e.ionizationEnergy < prev;
});

